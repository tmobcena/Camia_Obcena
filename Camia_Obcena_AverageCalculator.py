activity1 = float(input("Enter your grade for Activity 1: "))
activity2 = float(input("Enter your grade for Activity 2: "))
activity3 = float(input("Enter your grade for Activity 3: "))

sum = activity1 + activity2 + activity3
average = sum / 3

print(f"\nYour average is: {average:.2f}")

